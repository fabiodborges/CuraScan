-- Pricing helper view for the app
CREATE OR REPLACE VIEW public.pricing AS
SELECT
  30 AS duration_minutes, 8.00 AS price_client, 6.40 AS price_waiter, 1.60 AS commission
UNION ALL SELECT 60, 15.00, 12.00, 3.00
UNION ALL SELECT 90, 22.00, 17.60, 4.40
UNION ALL SELECT 120, 28.00, 22.40, 5.60
UNION ALL SELECT 150, 35.00, 28.00, 7.00
UNION ALL SELECT 180, 41.00, 32.80, 8.20
UNION ALL SELECT 210, 47.00, 37.60, 9.40
UNION ALL SELECT 240, 53.00, 42.40, 10.60;
